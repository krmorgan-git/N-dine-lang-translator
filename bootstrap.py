#!/usr/bin/env python3
"""
Bootstrap the N-dine-lang project layout (Linux / WSL).

Idempotently creates:
  - md/               Markdown notes/output directory
  - .env              Google Gemini API key template (git-ignored)
  - requirements.txt  dependency manifest (no third-party packages)

`csv/`, `db/`, and `models/` are supplied by the repository or created by
app.py at runtime, so bootstrap.py does not touch them.

Existing files are left untouched unless --force is given.

Usage:
    python bootstrap.py [--force]
"""

import sys
from pathlib import Path
from typing import List, Optional

ROOT = Path(__file__).resolve().parent
MD_DIR = ROOT / "md"
ENV_FILE = ROOT / ".env"
REQUIREMENTS_FILE = ROOT / "requirements.txt"

ENV_TEMPLATE = """\
# N-dine-lang-translator environment configuration
# Generated by bootstrap.py. This file is git-ignored — never commit it.
#
# Google Gemini API key (create one at https://aistudio.google.com/apikey)
GEMINI_API_KEY=
"""

REQUIREMENTS_TEMPLATE = """\
# N-dine-lang-translator dependencies
google-genai
python-dotenv
flask
llama-cpp-python
huggingface_hub
"""


def ensure_dir(path: Path) -> bool:
    """Create a directory if missing. Returns True when it was created."""
    if path.is_dir():
        return False
    path.mkdir(parents=True)
    return True


def write_template(path: Path, content: str, force: bool) -> str:
    """Write content to path. Returns 'created', 'overwritten', or 'kept'."""
    if path.exists() and not force:
        return "kept"
    existed = path.exists()
    path.write_text(content, encoding="utf-8")
    return "overwritten" if existed else "created"


def parse_args(argv: List[str]) -> bool:
    """Return True when --force was requested; exit on unknown arguments."""
    unknown = [arg for arg in argv if arg != "--force"]
    if unknown:
        sys.stderr.write("Unknown argument(s): %s\n" % " ".join(unknown))
        sys.stderr.write("Usage: python bootstrap.py [--force]\n")
        raise SystemExit(2)
    return "--force" in argv


def main(argv: Optional[List[str]] = None) -> int:
    force = parse_args(argv if argv is not None else sys.argv[1:])

    print("Project root: %s" % ROOT)

    for directory in (MD_DIR,):
        created = ensure_dir(directory)
        print("  %-11s %s/" % ("created" if created else "exists", directory.relative_to(ROOT)))

    for path, template in (
        (ENV_FILE, ENV_TEMPLATE),
        (REQUIREMENTS_FILE, REQUIREMENTS_TEMPLATE),
    ):
        status = write_template(path, template, force)
        print("  %-11s %s" % (status, path.relative_to(ROOT)))

    print("")
    print("Recommended: run ./start.sh (Linux/macOS/WSL) or start.bat (Windows).")
    print("Manual next steps:")
    print("  1. python3 -m venv .venv")
    print("  2. source .venv/bin/activate")
    print("  3. pip install -r requirements.txt")
    print("  4. python app.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
